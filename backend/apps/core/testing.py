def make_request(citizen, **overrides):
    """Create a pending request through the service layer (so audit rows exist too)."""
    data = {**REQUEST_PAYLOAD, **overrides}
    return services.create_request(citizen=citizen, **data)


def image_bytes(fmt="PNG", size=(40, 30), color=(200, 40, 40), **save_kwargs):
    buffer = io.BytesIO()
    Image.new("RGB", size, color).save(buffer, format=fmt, **save_kwargs)
    return buffer.getvalue()


def image_upload(name="photo.png", fmt="PNG", content_type=None, size=(40, 30), data=None, **save_kwargs):
    """Build an uploadable image file. ``data`` overrides the generated bytes."""
    default_types = {"PNG": "image/png", "JPEG": "image/jpeg", "WEBP": "image/webp", "GIF": "image/gif"}
    return SimpleUploadedFile(
        name,
        data if data is not None else image_bytes(fmt, size, **save_kwargs),
        content_type=content_type or default_types.get(fmt, "application/octet-stream"),
    )


def read_streamed(response):
    """Consume a streaming (file) response so its file handle is released.

    Matters on Windows, where an open handle prevents the temp media dir being cleaned up.
    Do NOT call ``response.close()`` as well: Django's test client already closes the response
    once the stream is exhausted, and a second close fires ``request_finished`` again, which
    makes Django close the (test-transaction) database connection on real database servers.
    """
    return b"".join(response.streaming_content)


class BaseAPITestCase(APITestCase):
    """API test case with an isolated media directory and a clean throttle cache."""

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls._media_dir = tempfile.mkdtemp(prefix="sr-test-media-")
        cls._media_override = override_settings(MEDIA_ROOT=cls._media_dir)
        cls._media_override.enable()

    @classmethod
    def tearDownClass(cls):
        cls._media_override.disable()
        shutil.rmtree(cls._media_dir, ignore_errors=True)
        super().tearDownClass()

    def setUp(self):
        super().setUp()
        cache.clear()  # reset login/register throttle counters between tests
        # Each test starts with an empty media directory (the DB is rolled back per test; files are not).
        for entry in os.scandir(self._media_dir):
            shutil.rmtree(entry.path) if entry.is_dir() else os.remove(entry.path)
